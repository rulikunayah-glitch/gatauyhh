with gr.Blocks(theme=gr.themes.Soft(), title="Wear Reworn") as demo:
    gr.Markdown(
        "# WEAR REWORN\n"
        "### Preloved clothing | Carefully chosen\n"
        "Temukan outfit favoritmu!"
    )

    cart = gr.State({})

    with gr.Tab("Beranda & Produk"):
        gr.Markdown("## Katalog Produk")
        gr.Markdown(katalog())

    with gr.Tab("Detail & Keranjang"):
        pilihan = gr.Dropdown(
            choices=list(produk.keys()),
            value="1",
            label="Pilih Produk",
            info="1 = Cardigan, 2 = Denim Skirt, 3 = Tanktop"
        )
        info_produk = gr.Markdown(detail("1"))
        pilihan.change(detail, pilihan, info_produk)

        jumlah = gr.Number(label="Jumlah", value=1, precision=0)
        btn_tambah = gr.Button("Tambah ke Keranjang", variant="primary")
        pesan_tambah = gr.Markdown()

        btn_tambah.click(
            tambah,
            inputs=[pilihan, jumlah, cart],
            outputs=[cart, pesan_tambah]
        )

        gr.Markdown("---")
        isi_keranjang = gr.Markdown("Keranjang masih kosong.")
        btn_lihat = gr.Button("Lihat Keranjang")
        btn_lihat.click(tampilan_keranjang, cart, isi_keranjang)

        hapus_pilihan = gr.Dropdown(
            choices=list(produk.keys()),
            label="Pilih produk yang akan dihapus"
        )
        btn_hapus = gr.Button("Hapus Produk")
        pesan_hapus = gr.Markdown()

        btn_hapus.click(
            hapus,
            inputs=[hapus_pilihan, cart],
            outputs=[cart, pesan_hapus]
        ).then(tampilan_keranjang, cart, isi_keranjang)

    with gr.Tab("Checkout"):
        gr.Markdown("## Data Pembeli")
        nama = gr.Textbox(label="Nama Penerima")
        telepon = gr.Textbox(label="Nomor Telepon")
        alamat = gr.Textbox(label="Alamat Lengkap", lines=3)

        kurir = gr.Radio(
            ["Reguler", "Express"],
            value="Reguler",
            label="Pilihan Pengiriman"
        )

        metode = gr.Radio(
            ["Transfer (Simulasi)", "COD"],
            value="Transfer (Simulasi)",
            label="Metode Pembayaran"
        )

        btn_checkout = gr.Button("Buat Pesanan", variant="primary")
        hasil = gr.Markdown()

        btn_checkout.click(
            checkout,
            inputs=[nama, telepon, alamat, kurir, metode, cart],
            outputs=hasil
        ).then(
            lambda: {},
            outputs=cart
        ).then(
            tampilan_keranjang,
            cart,
            isi_keranjang
        )

    gr.Markdown(
        "---\n"
        "Wear Reworn | Demo website toko pakaian preloved\n"
        "Pembayaran dan ongkir hanya simulasi."
    )

demo.launch(share=True)