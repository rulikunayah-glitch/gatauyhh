import gradio as gr
from datetime import datetime
import random

# =========================
# DATA PRODUK
# =========================

produk = {
    "1": {
        "nama": "Korean Cardigan",
        "harga": 85000,
        "ukuran": "M",
        "kondisi": "Preloved - Good Condition",
        "stok": 5,
        "foto": "https://placehold.co/400x300?text=Cardigan"
    },
    "2": {
        "nama": "Vintage Denim Skirt",
        "harga": 55000,
        "ukuran": "S",
        "kondisi": "Preloved - Very Good",
        "stok": 3,
        "foto": "https://placehold.co/400x300?text=Denim+Skirt"
    },
    "3": {
        "nama": "Basic Tanktop",
        "harga": 25000,
        "ukuran": "All Size",
        "kondisi": "Preloved - Good Condition",
        "stok": 8,
        "foto": "https://placehold.co/400x300?text=Tanktop"
    }
}

def rupiah(angka):
    return "Rp" + f"{angka:,}".replace(",", ".")

def katalog():
    hasil = "# WEAR REWORN\n### Little finds, carefully chosen\n\n"
    for id, p in produk.items():
        hasil += (
            f"### {p['nama']}\n"
            f"![Produk]({p['foto']})\n\n"
            f"**Harga:** {rupiah(p['harga'])}  \n"
            f"**Ukuran:** {p['ukuran']}  \n"
            f"**Kondisi:** {p['kondisi']}  \n"
            f"**Stok:** {p['stok']} pcs\n\n---\n"
        )
    return hasil

def detail(id):
    if not id:
        return "Pilih produk terlebih dahulu."
    p = produk[id]
    return (
        f"## {p['nama']}\n"
        f"![Produk]({p['foto']})\n\n"
        f"**Harga:** {rupiah(p['harga'])}\n\n"
        f"**Ukuran:** {p['ukuran']}\n\n"
        f"**Kondisi:** {p['kondisi']}\n\n"
        f"**Stok:** {p['stok']} pcs"
    )

def tambah(id, jumlah, cart):
    cart = dict(cart or {})
    if not id:
        return cart, "Pilih produk dahulu."
    jumlah = int(jumlah)
    tersedia = produk[id]["stok"]
    sudah = cart.get(id, 0)

    if jumlah < 1:
        return cart, "Jumlah harus minimal 1."
    if sudah + jumlah > tersedia:
        return cart, "Stok tidak mencukupi."

    cart[id] = sudah + jumlah
    return cart, "Produk berhasil ditambahkan ke keranjang."

def tampilan_keranjang(cart):
    cart = cart or {}
    if not cart:
        return "Keranjang masih kosong."

    teks = "## Keranjang Belanja\n\n"
    total = 0
    for id, jumlah in cart.items():
        p = produk[id]
        subtotal = p["harga"] * jumlah
        total += subtotal
        teks += (
            f"- **{p['nama']}** x{jumlah} "
            f"= {rupiah(subtotal)}\n"
        )
    teks += f"\n### Total: {rupiah(total)}"
    return teks

def hapus(id, cart):
    cart = dict(cart or {})
    if id and id in cart:
        del cart[id]
        return cart, "Produk dihapus dari keranjang."
    return cart, "Produk tidak ditemukan di keranjang."

def checkout(nama, telepon, alamat, kurir, metode, cart):
    cart = dict(cart or {})

    if not cart:
        return "Keranjang masih kosong."
    if not nama.strip() or not telepon.strip() or not alamat.strip():
        return "Lengkapi nama, nomor telepon, dan alamat."
    if not telepon.strip().replace("+", "").replace("-", "").replace(" ", "").isdigit():
        return "Nomor telepon tidak valid."

    # Validasi ulang stok
    for id, jumlah in cart.items():
        if jumlah > produk[id]["stok"]:
            return f"Stok {produk[id]['nama']} tidak mencukupi."

    subtotal = sum(produk[id]["harga"] * qty
                   for id, qty in cart.items())

    # Simulasi ongkir
    ongkir = {"Reguler": 15000, "Express": 25000}[kurir]
    total = subtotal + ongkir
    nomor = "WR" + datetime.now().strftime("%y%m%d%H%M%S") + str(random.randint(10,99))

    rincian = ""
    for id, qty in cart.items():
        p = produk[id]
        rincian += f"- {p['nama']} x{qty}\n"

    # Stok dikurangi saat pesanan dibuat
    for id, qty in cart.items():
        produk[id]["stok"] -= qty

    if metode == "Transfer (Simulasi)":
        status = "Menunggu Pembayaran (Simulasi)"
        info = "Silakan lakukan pembayaran sesuai instruksi toko. Belum ada pembayaran nyata."
    else:
        status = "Menunggu Konfirmasi"
        info = "Pesanan COD menunggu konfirmasi toko."

    return (
        f"# Pesanan Berhasil Dibuat!\n\n"
        f"**Nomor pesanan:** {nomor}\n\n"
        f"**Nama:** {nama}\n\n"
        f"**Telepon:** {telepon}\n\n"
        f"**Alamat:** {alamat}\n\n"
        f"**Produk:**\n{rincian}\n"
        f"**Subtotal:** {rupiah(subtotal)}\n\n"
        f"**Kurir:** {kurir}\n\n"
        f"**Ongkir (simulasi):** {rupiah(ongkir)}\n\n"
        f"**Total:** {rupiah(total)}\n\n"
        f"**Pembayaran:** {metode}\n\n"
        f"**Status:** {status}\n\n"
        f"{info}"
    )

