import ipywidgets as widgets
from IPython.display import display, clear_output
import random

# Judul
print("👑 AJAKAN NGOPI BERSAMA PRINCESS KANIA ☕\n" + "="*40)

# Input Nama
input_nama = widgets.Text(
    value='',
    placeholder='Tulis nama kamu di sini...',
    description='Nama:',
    disabled=False
)

# Tombol Pilihan Jawaban
btn_free = widgets.Button(
    description='Free sih 😊',
    button_style='info', # Warna biru muda
    icon='coffee'
)

btn_free_kania = widgets.Button(
    description='Free trs buat Kania 💖',
    button_style='danger', # Warna pink/merah
    icon='heart'
)

output = widgets.Output()

# Daftar Tempat Ngopi Khusus (Random Antara Mosu dan Kru)
daftar_tempat = [
    "Mosu ☕✨",
    "Kru ☕✨"
]

def respon_free(b):
    with output:
        clear_output()
        nama = input_nama.value if input_nama.value else "Kamu"
        tempat = random.choice(daftar_tempat)
        print(f"\n🎉 yeyyy {nama}! Jadi besok kamu: 'Free sih'!")
        print(f"📍 Tempat ngopi pilihan kita : {tempat}")
        print(f" jangan lupa kalo lupa aku cubit")

def respon_free_kania(b):
    with output:
        clear_output()
        nama = input_nama.value if input_nama.value else "Kamu"
        tempat = random.choice(daftar_tempat)
        print(f"\n💖 Aww sweet banget! {nama} bilang: 'Free trs buat Kania' 🥰👩‍❤️‍👨")
        print(f"📍 Tempat ngopi spesial pilihan kita: {tempat}")
        print(f" jangan lupa kalo lupa aku banting km")


btn_free.on_click(respon_free)
btn_free_kania.on_click(respon_free_kania)

# Menampilkan Form Interaktif
display(input_nama)
print("\nPertanyaan: Besok free ga?")
display(widgets.HBox([btn_free, btn_free_kania]))
display(output)